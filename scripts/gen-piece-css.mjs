// Generates piece-set CSS + registry from assets/pieces/ (single source of
// truth: one sub-directory per piece set, holding the 14 standard SVGs
// wking wadvisor wbishop wrook wknight wcannon wpawn + black counterparts).
//
//   node scripts/gen-piece-css.mjs          generate (write files)
//   node scripts/gen-piece-css.mjs --check  verify outputs are up to date
//
// Outputs (all committed to the repo, bundled into styles.css by Vite):
//   src/style/pieceSets/<set>.css  14 board rules + 2 thumbnail rules,
//                                  base64 data URIs scoped under
//                                  .xq-pieceset-<set>
//   src/style/pieceSets/index.css  @import list
//   src/pieceSets.gen.ts           PIECE_SETS registry for settings UI
//
// The base artwork of the default ("traditional") set is identical to
// @weshell/xiangqiground's bundled xiangqiground.piece.css — its generated
// rules simply override the bundled ones at a higher specificity, mirroring
// how the chess repo handles cburnett.
//
// Directories missing any of the 14 standard files are skipped with a
// warning — add or remove a set by adding or removing its directory, then
// re-run this script.

import {
  readFileSync,
  writeFileSync,
  existsSync,
  readdirSync,
  mkdirSync,
  rmSync,
} from "node:fs";
import { join } from "node:path";

const ROOT = import.meta.dirname;
const SRC_DIR = join(ROOT, "..", "assets", "pieces");
const CSS_DIR = join(ROOT, "..", "src", "style", "pieceSets");
const INDEX_CSS = join(CSS_DIR, "index.css");
const GEN_TS = join(ROOT, "..", "src", "pieceSets.gen.ts");

const CHECK = process.argv.includes("--check");

// The 14 standard piece images every set must provide. File name is
// <w|b><role>.svg; the letter codes map to chessground element classes
// (e.g. wknight -> piece.knight.white).
const ROLES = ["king", "advisor", "bishop", "rook", "knight", "cannon", "pawn"];
const PIECE_FILES = [];
for (const w of ["w", "b"]) {
  for (const role of ROLES) PIECE_FILES.push(`${w}${role}`);
}

const COLOR = { w: "white", b: "black" };

// Thumbnail preview files (shown in the board-menu picker).
const THUMB_FILES = ["wknight", "bknight"];

// Must match CLS_PREFIX in ../src/chess.ts.
const CLS_PREFIX = "xq";

// Canonical display order.
const CANONICAL_ORDER = ["traditional", "letter", "blind"];

// Display names (Chinese-first audience; the plugin's default language is zh).
const DISPLAY_NAMES = {
  traditional: "传统",
  letter: "字母",
  blind: "盲棋",
};

const AUTO_HEADER =
  "Generated by scripts/gen-piece-css.mjs — DO NOT EDIT. Re-run the script after changing assets/pieces/.";

function dataUri(file) {
  const bin = readFileSync(file);
  return `url("data:image/svg+xml;base64,${bin.toString("base64")}")`;
}

function pieceFile(dir, code) {
  const file = join(dir, `${code}.svg`);
  return existsSync(file) ? file : null;
}

// ---- collect valid sets -----------------------------------------------------

if (!existsSync(SRC_DIR)) {
  console.error(`Source directory not found: ${SRC_DIR}`);
  process.exit(1);
}

const sets = [];
for (const entry of readdirSync(SRC_DIR, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const dir = join(SRC_DIR, entry.name);
  const missing = PIECE_FILES.filter((code) => pieceFile(dir, code) === null);
  if (missing.length > 0) {
    console.warn(`SKIP ${entry.name}/ — missing: ${missing.join(", ")}`);
    continue;
  }
  sets.push(entry.name);
}

sets.sort((a, b) => {
  const ia = CANONICAL_ORDER.indexOf(a);
  const ib = CANONICAL_ORDER.indexOf(b);
  if (ia === -1 && ib === -1) return a.localeCompare(b);
  if (ia === -1) return 1;
  if (ib === -1) return -1;
  return ia - ib;
});

if (sets.length === 0) {
  console.error("No valid piece sets found.");
  process.exit(1);
}

// ---- build outputs ----------------------------------------------------------

const outputs = new Map(); // path -> content

for (const set of sets) {
  const dir = join(SRC_DIR, set);
  let css = `/* ${AUTO_HEADER} Source: assets/pieces/${set}/ */\n`;
  for (const code of PIECE_FILES) {
    const color = COLOR[code[0]];
    const role = code.slice(1);
    css += `.${CLS_PREFIX}-pieceset-${set} .xq-wrap piece.${role}.${color} {\n  background-image: ${dataUri(pieceFile(dir, code))};\n}\n`;
  }
  // Thumbnail rules must require the scope class ON the picker tile itself
  // (`.<prefix>-piece-set-picker__tile.<prefix>-pieceset-<set>`):
  // applyPieceSet() keeps a `.<prefix>-pieceset-<current>` class on <body>,
  // and a plain descendant selector would let the body-level rule leak into
  // every tile of the picker and override their own artwork.
  for (const code of THUMB_FILES) {
    css += `.${CLS_PREFIX}-piece-set-picker__tile.${CLS_PREFIX}-pieceset-${set} .${CLS_PREFIX}-piece-thumb.${code} {\n  background-image: ${dataUri(pieceFile(dir, code))};\n}\n`;
  }
  outputs.set(join(CSS_DIR, `${set}.css`), css);
}

outputs.set(
  INDEX_CSS,
  `/* ${AUTO_HEADER} */\n${sets.map((set) => `@import "./${set}.css";\n`).join("")}`,
);

const registry = sets.map(
  (set) => `  { key: "${set}", name: "${DISPLAY_NAMES[set] ?? set}" },`,
);
outputs.set(
  GEN_TS,
  `// ${AUTO_HEADER}\n\nexport interface PieceSetDef {\n  key: string;\n  name: string;\n}\n\nexport const PIECE_SETS: readonly PieceSetDef[] = [\n${registry.join("\n")}\n];\n`,
);

// ---- write or check ---------------------------------------------------------

mkdirSync(CSS_DIR, { recursive: true });

let failures = 0;

// Orphaned per-set CSS files (their source directory was removed/renamed).
for (const file of readdirSync(CSS_DIR)) {
  if (!file.endsWith(".css")) continue;
  if (outputs.has(join(CSS_DIR, file))) continue;
  if (CHECK) {
    console.error(`ORPHAN: ${join(CSS_DIR, file)}`);
    failures++;
  } else {
    rmSync(join(CSS_DIR, file));
    console.log(`DELETE: ${join(CSS_DIR, file)}`);
  }
}
for (const [path, content] of outputs) {
  const existing = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (existing === content) continue;
  if (CHECK) {
    console.error(`STALE: ${path}`);
    failures++;
  } else {
    writeFileSync(path, content);
    console.log(`WRITE: ${path}`);
  }
}

if (CHECK) {
  if (failures > 0) {
    console.error(
      `${failures} generated file(s) out of date — re-run: node scripts/gen-piece-css.mjs`,
    );
    process.exit(1);
  }
  console.log(
    `OK — ${sets.length} piece sets, all generated files up to date.`,
  );
} else {
  console.log(`Done — ${sets.length} piece sets generated.`);
}
