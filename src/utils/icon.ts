export const ANNOTATION_KEYS = ["++", "--", "==", "bm", "st"];

const OLD_KEY_MAP: Record<string, string> = {
  "W+": "++",
  "B+": "--",
  "=": "==",
  "?": "bm",
  "!": "st",
  "W#": "++",
  "B#": "--",
  "=#": "==",
};

export function normalizeAnnotationKey(key: string): string {
  return OLD_KEY_MAP[key] ?? key;
}

export function isAnnotationKey(key: string): boolean {
  return ANNOTATION_KEYS.includes(key) || key in OLD_KEY_MAP;
}

export function isBadgeKey(key: string): boolean {
  return key in BADGE_DEFS;
}

export function badgeSvg(key: string, size: number = 6): string {
  const def = BADGE_DEFS[normalizeAnnotationKey(key)];
  if (!def) return "";
  const r = size / 2;
  let inner = "";
  if (def.glyph) {
    const s = size / 100;
    inner = `<g transform="translate(${-r},${-r}) scale(${s})">${def.glyph}</g>`;
  } else if (def.icon) {
    const nodes = ICONS[def.icon];
    if (nodes) {
      const iconR = r * 0.7;
      const s = (iconR * 2) / 24;
      const children = nodes
        .map(([tag, attrs]) => {
          const attrStr = Object.entries(attrs)
            .map(([k, v]) => `${k}="${v}"`)
            .join(" ");
          return `<${tag} ${attrStr}/>`;
        })
        .join("");
      inner = `<g transform="translate(${-iconR},${-iconR}) scale(${s})" fill="none" stroke="${def.fgColor}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${children}</g>`;
    }
  }
  return `<circle cx="0" cy="0" r="${r}" fill="${def.bgColor}"/>${inner}`;
}

export function badgeBoardSvg(key: string, stack: number = 0): string {
  const def = BADGE_DEFS[normalizeAnnotationKey(key)];
  if (!def) return "";
  const x = -12;
  const y = stack > 0 ? 68 : -12;
  let inner = "";
  if (def.glyph) {
    inner = def.glyph;
  } else if (def.icon) {
    const nodes = ICONS[def.icon];
    if (nodes) {
      inner = nodes
        .map(([tag, attrs]) => {
          const attrStr = Object.entries(attrs)
            .map(([k, v]) => `${k}="${v}"`)
            .join(" ");
          return `<${tag} ${attrStr} fill="none" stroke="#fff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>`;
        })
        .join("");
      inner = `<g transform="translate(14,14) scale(3)">${inner}</g>`;
    }
  }
  return `<g transform="matrix(.4 0 0 .4 ${x} ${y})"><circle cx="50" cy="50" r="50" fill="${def.bgColor}"/>${inner}</g>`;
}

export function iconPaths(name: string): string {
  const nodes = ICONS[name];
  if (!nodes) return "";
  return nodes
    .map(([tag, attrs]) => {
      const attrStr = Object.entries(attrs)
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${attrStr}/>`;
    })
    .join("");
}

export function iconSvg(
  name: string,
  size: number = 24,
  strokeWidth: number = 2,
  fill: string = "none",
): string {
  const nodes = ICONS[name];
  if (!nodes) return "";
  const children = nodes
    .map(([tag, attrs]) => {
      const attrStr = Object.entries(attrs)
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `    <${tag} ${attrStr}/>`;
    })
    .join("\n");
  return [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24"`,
    `  fill="${fill}" stroke="currentColor" stroke-width="${strokeWidth}"`,
    '  stroke-linecap="round" stroke-linejoin="round">',
    children,
    "</svg>",
  ].join("\n");
}
